def _stub_by_egress(monkeypatch: pytest.MonkeyPatch, *, direct, proxy) -> list[str]:
    """Answer each egress leg with `(status, body, headers)` or raise an exception.

    Returns the sequence of `egress` values the route asked for. A leg the
    route never names ("auto") is a KeyError on purpose: the whole fix is
    that the route chooses the leg explicitly.
    """
    outcomes = {"direct": direct, "proxy": proxy}
    seen: list[str] = []

    async def fake_get(
        self, url, headers=None, cookies=None, params=None, timeout=None, egress="auto", **kwargs
    ):
        seen.append(egress)
        outcome = outcomes[egress]
        if isinstance(outcome, BaseException):
            raise outcome
        status, body, response_headers = outcome
        return AsyncHttpResponse(
            status_code=status, text=body, headers=dict(response_headers), url=url
        )

    monkeypatch.setattr("app.core.http_client.AsyncHttpClient.get", fake_get)
    return seen


class FakeClock:
    def __init__(self, start: float = 1000.0) -> None:
        self.now = start

    def __call__(self) -> float:
        return self.now

    def advance(self, seconds: float) -> None:
        self.now += seconds


