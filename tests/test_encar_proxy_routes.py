def test_cooldown_expiry_routes_direct_again_and_resets_on_success(
    client: TestClient, monkeypatch: pytest.MonkeyPatch
) -> None:
    _arm_failover(monkeypatch)
    clock = FakeClock()
    encar_proxy._breaker = EgressBreaker(600, clock=clock)
    legs = _stub_by_egress(monkeypatch, direct=CLOUDFRONT_403, proxy=OK_200)
    assert client.get("/api/catalog", params={"sr": "|ModifiedDate|0|21"}).status_code == 200
    assert legs == ["direct", "proxy"]

    clock.advance(601)
    infos: list[str] = []
    monkeypatch.setattr(encar_proxy.logger, "info", lambda m, *a, **k: infos.append(str(m)))
    legs = _stub_by_egress(monkeypatch, direct=OK_200, proxy=OK_200)
