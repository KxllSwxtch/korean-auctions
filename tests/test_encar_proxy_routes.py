def test_non_2xx_is_never_cached(
    client: TestClient, monkeypatch: pytest.MonkeyPatch
) -> None:
    outcomes = [(404, '{"message":"not found"}'), (200, UPSTREAM_BODY)]
    calls: list[str] = []

    async def fake_get(
        self, url, headers=None, cookies=None, params=None, timeout=None, egress="auto", **kwargs
    ):
        calls.append(url)
        status, body = outcomes[len(calls) - 1]
        return AsyncHttpResponse(status_code=status, text=body, headers={}, url=url)

    monkeypatch.setattr("app.core.http_client.AsyncHttpClient.get", fake_get)

    first = client.get("/api/nav", params={"q": NAV_QUERY})
    second = client.get("/api/nav", params={"q": NAV_QUERY})

    assert first.status_code == 404
    assert second.status_code == 200
