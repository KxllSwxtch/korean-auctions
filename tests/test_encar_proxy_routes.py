# ═══ The 2026-08-29 outage: CloudFront blocks Render's egress ═══════════════
#
# api.encar.com's edge answers every direct request from Render with 403
# "Request blocked" HTML. Before the fix _forward relayed that HTML verbatim as
# application/json and the catalog died. The Korean residential pool in
# AUCTION_PROXY_* was configured the whole time; these tests pin that the route
